/*
 * Copies Minecraft's own item textures into public/items/, one PNG per item id.
 *
 * The marketplace names items the way Minecraft does (diamond_pickaxe), so the icon for a stack is simply
 * /items/<id>.png. Real 16x16 textures, drawn by the people who drew the game.
 *
 * Source: the minecraft-assets package (PrismarineJS, MIT). It is a devDependency: this script runs by hand, the
 * result is committed, and the running site keeps its zero runtime dependencies.
 *
 * The textures themselves belong to Mojang. They are used here the way every Minecraft fan site and wiki uses them.
 *
 * Run: node scripts/build-item-icons.mjs [version]
 */
import { copyFile, mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VERSION = process.argv[2] ?? "1.21.11";
const DATA = path.join(ROOT, "node_modules", "minecraft-assets", "minecraft-assets", "data", VERSION);
const OUT = path.join(ROOT, "public", "items");

/** Where a texture reference such as `minecraft:block/stone` actually lives on disk. */
async function resolveTexture(reference) {
  const clean = reference.replace(/^minecraft:/, "");
  const candidates = [clean, clean.replace(/^block\//, "blocks/"), clean.replace(/^item\//, "items/")];
  for (const candidate of candidates) {
    const file = path.join(DATA, `${candidate}.png`);
    try {
      if ((await stat(file)).isFile()) {
        return file;
      }
    } catch {
      // try the next spelling
    }
  }
  return null;
}

async function main() {
  try {
    await stat(DATA);
  } catch {
    console.error(`No assets for ${VERSION}. Run "npm install" first, or pass a version that exists in`);
    console.error(path.join(ROOT, "node_modules", "minecraft-assets", "minecraft-assets", "data"));
    process.exitCode = 1;
    return;
  }

  const items = JSON.parse(
    await (await import("node:fs/promises")).readFile(path.join(DATA, "items_textures.json"), "utf8"),
  );

  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  let copied = 0;
  let bytes = 0;
  const missing = [];
  for (const entry of items) {
    const name = entry?.name;
    const reference = entry?.texture;
    // air has no icon, and "missingno" is the texture Minecraft shows when it has none either
    if (typeof name !== "string" || typeof reference !== "string" || reference.endsWith("missingno")) {
      continue;
    }
    const source = await resolveTexture(reference);
    if (!source) {
      missing.push(name);
      continue;
    }
    const target = path.join(OUT, `${name}.png`);
    await copyFile(source, target);
    bytes += (await stat(target)).size;
    copied++;
  }

  // the page asks for /items/<id>.png directly, so it needs to know which ids exist before requesting one
  const names = (await readdir(OUT)).filter((file) => file.endsWith(".png")).map((file) => file.slice(0, -4));
  await writeFile(path.join(ROOT, "src", "generated", "item-icons.ts"), render(names, VERSION));

  console.log(`${copied} item textures from Minecraft ${VERSION} → public/items (${Math.round(bytes / 1024)} KB)`);
  if (missing.length > 0) {
    console.log(`${missing.length} item(s) have no texture of their own: ${missing.slice(0, 8).join(", ")}…`);
  }
}

function render(names, version) {
  return `/*
 * Generated by scripts/build-item-icons.mjs from Minecraft ${version} — do not edit by hand.
 *
 * Every item id that has a texture in public/items. The page checks this set before pointing an <img> at a file, so a
 * missing icon is a placeholder rather than a broken image and a request that 404s.
 */
export const ITEM_ICONS: ReadonlySet<string> = new Set([
${names.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
]);
`;
}

await main();
