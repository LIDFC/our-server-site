/**
 * Builds the Russian names of Minecraft items from the plugin's own dictionary.
 *
 * <p>The marketplace plugin already knows how to call an item in Russian: its catalogue window lets a player type
 * «алмаз» and find diamonds. That dictionary is three ordered lists in one Java file, and copying it by hand into the
 * website would guarantee the two drift apart — the site would find items the game does not, and vice versa, which
 * is exactly the sort of difference nobody notices until somebody cannot find their own stack.
 *
 * <p>So it is read out of the plugin's source instead, and the result is committed, like the item textures are. The
 * site builds without the plugin checked out; only regenerating needs it.
 *
 *   node scripts/build-item-names.mjs [path to our-server-market]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, "..");
const plugin = resolve(site, process.argv[2] ?? "../our-server-market");
const source = resolve(plugin, "src/main/java/site/vinoff/market/gui/Catalogue.java");
const output = resolve(site, "src/generated/item-names.ts");

let java;
try {
  java = readFileSync(source, "utf8");
} catch {
  console.error(`Cannot read ${source}`);
  console.error("Point this at the plugin repository: node scripts/build-item-names.mjs ../our-server-market");
  process.exit(1);
}

/** Pulls `kind("id", "слово");` out of the Java, keeping the order the file puts them in. */
function entries(kind) {
  const pattern = new RegExp(`${kind}\\("([^"]+)",\\s*"([^"]+)"\\);`, "g");
  const found = [];
  for (const match of java.matchAll(pattern)) {
    found.push([match[1], match[2]]);
  }
  if (found.length === 0) {
    console.error(`No ${kind} entries found; has Catalogue.java changed shape?`);
    process.exit(1);
  }
  return found;
}

const prefixes = entries("prefix");
const suffixes = entries("suffix");
const exact = entries("exact");

const list = (pairs) => pairs.map(([id, word]) => `  ["${id}", "${word}"],`).join("\n");

const text = `/*
 * Generated by scripts/build-item-names.mjs from the marketplace plugin's Catalogue.java — do not edit by hand.
 *
 * The same dictionary the game uses, so searching «алмаз» on the website finds what searching «алмаз» in the game
 * finds. Run the script again after the plugin's catalogue changes.
 */

/** Colours and wood types: the first half of a made up name. */
export const NAME_PREFIXES: ReadonlyMap<string, string> = new Map([
${list(prefixes)}
]);

/** Categories: the second half. Longest first, so concrete powder is never read as concrete. */
export const NAME_SUFFIXES: readonly (readonly [string, string])[] = [
${list(suffixes)}
];

/** Items worth naming one by one: the things people actually put on a marketplace. */
export const NAME_EXACT: ReadonlyMap<string, string> = new Map([
${list(exact)}
]);
`;

writeFileSync(output, text);
console.log(
  `Wrote ${output}: ${prefixes.length} prefixes, ${suffixes.length} suffixes, ${exact.length} named items`,
);
